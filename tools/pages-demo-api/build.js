'use strict';
// Bundles the Frontend Demo PAWS API (browser.js + the real server/src API
// modules) into one self-contained browser script.
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..', '..');
const SHIMS = path.join(__dirname, 'shims');
const ALIASES = {
  'node:crypto': 'crypto.js', crypto: 'crypto.js', 'node:fs': 'fs.js', fs: 'fs.js', 'node:path': 'path.js', path: 'path.js',
  'node:perf_hooks': 'perf_hooks.js', 'node:async_hooks': 'async_hooks.js'
};
const UNAVAILABLE = /^(node:worker_threads|worker_threads|node:http|node:net|node:https|exceljs|unzipper|jszip|mssql(\/.*)?|msnodesqlv8|firebase-admin(\/.*)?|@azure\/.*)$/;

const shimPlugin = {
  name: 'paws-demo-shims',
  setup(build) {
    build.onResolve({ filter: /.*/ }, args => {
      if (ALIASES[args.path]) return { path: path.join(SHIMS, ALIASES[args.path]) };
      if (UNAVAILABLE.test(args.path)) return { path: path.join(SHIMS, 'unavailable.js') };
      return undefined;
    });
  }
};

async function buildDemoApi({ outfile, minify = true } = {}) {
  const esbuild = require('esbuild');
  const result = await esbuild.build({
    entryPoints: [path.join(__dirname, 'browser.js')],
    outfile,
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2020'],
    minify,
    legalComments: 'none',
    inject: [path.join(SHIMS, 'globals.js')],
    define: { __dirname: '"/pages-demo"', 'process.env.NODE_ENV': '"production"', global: 'globalThis' },
    nodePaths: [path.join(ROOT, 'node_modules'), path.join(ROOT, 'server', 'node_modules')],
    plugins: [shimPlugin],
    logLevel: 'warning',
    banner: { js: '/* UCVM PAWS Frontend Demo API — synthetic, browser-local data only. Generated by tools/pages-demo-api/build.js. */' }
  });
  return { outfile, warnings: result.warnings.length };
}

module.exports = { buildDemoApi };
if (require.main === module) {
  const out = process.argv[2] || path.join(ROOT, '.deploy-static', 'pages-demo-api.js');
  buildDemoApi({ outfile: out, minify: !process.argv.includes('--no-minify') }).then(r => console.log(JSON.stringify(r))).catch(error => { console.error(error); process.exit(1); });
}
